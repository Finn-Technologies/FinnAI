#!/usr/bin/env python3
"""Regenerates lib/src/features/voice/tts/supertonic_nfkd.dart.

usage: tool/gen_supertonic_nfkd.py path/to/unicode_indexer.json

Python's unicodedata does the NFKD decomposition; only the characters whose
decomposition the voice model can read (every resulting character has an entry
in its indexer) are emitted.
"""
import json
import sys
import unicodedata

index = json.load(open(sys.argv[1]))
rows = []
for cp in range(0x80, 0x3000):
    if 0xD800 <= cp <= 0xDFFF:
        continue
    decomposed = unicodedata.normalize('NFKD', chr(cp))
    if decomposed != chr(cp) and all(ord(c) < 65536 and index[ord(c)] >= 0 for c in decomposed):
        rows.append((cp, decomposed))
items = ['%x=%s' % (cp, ' '.join('%x' % ord(c) for c in d)) for cp, d in rows]
lines = [';'.join(items[i:i + 14]) for i in range(0, len(items), 14)]
body = '\n'.join("    '%s%s'" % (line, ';' if i < len(lines) - 1 else '') for i, line in enumerate(lines))
open('lib/src/features/voice/tts/supertonic_nfkd.dart', 'w').write(
    "// GENERATED by tool/gen_supertonic_nfkd.py from the voice's unicode_indexer.json.\n"
    "// Do not edit by hand.\n//\n"
    "// Unicode NFKD decomposition for the characters the Supertonic voice model can\n"
    "// read once decomposed (accented Latin and Cyrillic letters, ligatures, full\n"
    "// width forms, ...). Dart has no built-in normaliser and the model's character\n"
    "// table has no entry for, say, U+00E9, only for \"e\" followed by U+0301.\n"
    "//\n// Packed as `codepoint=codepoint codepoint;...` (hex) to keep the file short.\n\n"
    "const String _table =\n" + body + ";\n\n"
    "/// Code point -> what it decomposes to.\n"
    "final Map<int, String> supertonicNfkd = {\n"
    "  for (final entry in _table.split(';'))\n"
    "    int.parse(entry.split('=')[0], radix: 16): String.fromCharCodes([\n"
    "      for (final part in entry.split('=')[1].split(' '))\n"
    "        int.parse(part, radix: 16),\n"
    "    ]),\n"
    "};\n")
